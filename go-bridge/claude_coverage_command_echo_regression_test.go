// 2026-10-21 评审 MAJOR-1 handler 级回归：真实 claudecode.Agent + 真实形态
// transcript（尾部 /model 本地命令回显：caveat/command-name/local-command-stdout
// 行，2026-10-11 d9e61f32 同形）。冷 hydrate 后该 turn 必须结算 completed 且执行态
// 不标失败——修复前 d78100ee 扩语义把它计入 coverage，dead 进程下合成
// turn_aborted → 会话被标失败（评审 R1 MAJOR-1，main f868af18 对照为 completed）。

import (
	"context"
	"encoding/json"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/openAgi2/cordcode-macbridge/agent/claudecode"
)

func TestTrailingCommandEchoSettlesCompletedAfterHydrate(t *testing.T) {
	home := t.TempDir()
	t.Setenv("HOME", home)
	workDir := filepath.Join(home, "Projects", "echo-regression")
	projectDir := filepath.Join(home, ".claude", "projects", encodeProjectKey(workDir))
	if err := os.MkdirAll(projectDir, 0o755); err != nil {
		t.Fatal(err)
	}
	const sessionID = "echo-regression-session"
	lines := []string{
		`{"type":"user","uuid":"row-u1","timestamp":"2026-10-21T10:00:00Z","message":{"role":"user","content":"first prompt"}}`,
		`{"type":"assistant","uuid":"row-a1","timestamp":"2026-10-21T10:00:01Z","message":{"id":"msg_1","role":"assistant","content":[{"type":"text","text":"first answer"}],"stop_reason":"end_turn"}}`,
		`{"type":"user","uuid":"row-c0","isMeta":true,"timestamp":"2026-10-21T10:01:00Z","message":{"role":"user","content":"<local-command-caveat>Caveat: The messages below were generated by the user while running local commands. DO NOT respond.</local-command-caveat>"}}`,
		`{"type":"user","uuid":"row-c1","timestamp":"2026-10-21T10:01:00Z","message":{"role":"user","content":"<command-name>/model</command-name>\n<command-message>model</command-message>\n<command-args>haiku</command-args>"}}`,
		`{"type":"user","uuid":"row-c2","timestamp":"2026-10-21T10:01:01Z","message":{"role":"user","content":"<local-command-stdout>Set model to haiku</local-command-stdout>"}}`,
	}
	path := filepath.Join(projectDir, sessionID+".jsonl")
	if err := os.WriteFile(path, []byte(strings.Join(lines, "\n")+"\n"), 0o600); err != nil {
		t.Fatal(err)
	}

	raw, err := claudecode.New(map[string]any{"work_dir": workDir})
	if err != nil {
		t.Fatal(err)
	}
	agent := raw.(*claudecode.Agent)
	h := NewHandlers()
	t.Cleanup(func() { h.Shutdown(context.Background()) })
	h.RegisterAgent("claudecode", agent)

	conn := &readFileCaptureConn{}
	params, _ := json.Marshal(map[string]interface{}{"sessionId": sessionID, "directory": workDir})
	h.handleGetSessionProjection(conn, WireMessage{
		RequestID: "r-echo-regression", BackendID: "claude", Method: "get_session_projection", Params: params,
	}, agent)
	if conn.err != nil {
		t.Fatalf("projection pull failed: %+v", conn.err)
	}
	dataMap, ok := conn.data.(map[string]interface{})
	if !ok {
		t.Fatalf("data type %T", conn.data)
	}
	proj, ok := dataMap["projection"].(SessionProjection)
	if !ok {
		t.Fatalf("projection type %T", dataMap["projection"])
	}

	echo := ""
	echoStatus := ""
	for _, turn := range proj.Turns {
		if turn.Assistant == nil && turn.User != nil {
			for _, part := range turn.User.Parts {
				if part.Type == "text" && strings.HasPrefix(strings.TrimSpace(part.Text), "/model") {
					echo = turn.TurnID
					echoStatus = turn.Status
				}
			}
		}
	}
	if echo == "" {
		t.Fatalf("命令回显 turn 缺失（turns=%d）", len(proj.Turns))
	}
	if echoStatus != "completed" {
		t.Fatalf("尾部 /model 回显 turn %s status=%q want completed（2026-10-11 回归，评审 MAJOR-1）", echo, echoStatus)
	}
	if proj.Execution.Phase == "failed" || strings.Contains(proj.Execution.Phase, "fail") {
		t.Fatalf("会话执行态被标失败: %+v", proj.Execution)
	}
}
